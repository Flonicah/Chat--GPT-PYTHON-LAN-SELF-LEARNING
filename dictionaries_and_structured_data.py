# A Python dictionary stores data as key-value pairs.
# For example:
student = {
    "name": "Flonicah Phiri",
    "age": 26,
    "mark": 98
}

# "name" → key
# "Flonicah Phiri" → value
# "age" → key
# 26 → value
# "mark" → key
# 98 → value

# To access the values in a dictionary, you can use the keys. 
# For example:

print(student["name"])
print(student["age"])
print(student["mark"])

